"""Generate supabase/02_seed.sql: fake but realistic main-break data.

Deterministic (fixed random seed), so re-running gives identical rows and the
quiz answer key stays valid. Run: python scripts/generate_seed.py
"""

import random
from datetime import datetime, timedelta
from pathlib import Path

random.seed(706)

ZONES = ["Downtown", "Riverside", "Ridgecrest", "Mill Creek", "Airport"]
CREWS = [("Crew A", "Day"), ("Crew B", "Day"), ("Crew C", "Night"), ("Crew D", "Night")]

# material: (install-year range, typical diameters, relative break rate)
MATERIALS = {
    "Cast Iron": ((1925, 1965), [4, 6, 8, 12], 6.0),
    "Asbestos Cement": ((1952, 1980), [6, 8, 12], 3.5),
    "Ductile Iron": ((1966, 2000), [8, 12, 16, 24], 1.5),
    "PVC": ((1985, 2024), [4, 6, 8, 12], 0.8),
}
MATERIAL_MIX = ["Cast Iron"] * 62 + ["Asbestos Cement"] * 34 + ["Ductile Iron"] * 52 + ["PVC"] * 52

CAUSES_BY_MONTH_WINTER = ["Frost"] * 5 + ["Corrosion"] * 2 + ["Pressure Surge", "Ground Movement"]
CAUSES_OTHER = ["Corrosion"] * 4 + ["Ground Movement"] * 2 + ["Pressure Surge"] * 2 + ["Third-Party Damage"] * 2
TYPE_BY_CAUSE = {
    "Frost": ["Circumferential", "Circumferential", "Longitudinal"],
    "Corrosion": ["Corrosion Hole", "Corrosion Hole", "Longitudinal"],
    "Ground Movement": ["Circumferential", "Joint Leak"],
    "Pressure Surge": ["Longitudinal", "Joint Leak"],
    "Third-Party Damage": ["Longitudinal", "Corrosion Hole", "Joint Leak"],
}
METHOD_BY_TYPE = {
    "Circumferential": "Clamp",
    "Corrosion Hole": "Clamp",
    "Longitudinal": "Pipe Section Replacement",
    "Joint Leak": "Joint Repair",
}

START, END = datetime(2023, 1, 1), datetime(2025, 12, 31, 23, 0)


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def ts(d):
    return q(d.strftime("%Y-%m-%d %H:%M"))


mains = []
for i, mat in enumerate(MATERIAL_MIX, start=1):
    (y0, y1), diams, _ = MATERIALS[mat]
    mains.append(
        dict(
            main_id=100 + i,
            zone_id=random.randint(1, len(ZONES)),
            material=mat,
            diameter_in=random.choice(diams),
            length_ft=random.randrange(600, 6400, 50),
            install_year=random.randint(y0, y1),
        )
    )

# Break dates: weighted toward winter months.
days = []
d = START
while d <= END:
    w = 3.0 if d.month in (12, 1, 2) else 1.4 if d.month in (3, 11) else 1.0
    days.append((d, w))
    d += timedelta(days=1)

weights = [MATERIALS[m["material"]][2] * m["length_ft"] / 3000 for m in mains]
breaks, repairs = [], []
N_BREAKS = 120
picked_mains = random.choices(mains, weights=weights, k=N_BREAKS)
picked_days = sorted(random.choices([x[0] for x in days], weights=[x[1] for x in days], k=N_BREAKS))

for n, (m, day) in enumerate(zip(picked_mains, picked_days), start=1):
    reported = day + timedelta(hours=random.randint(0, 23), minutes=random.choice([0, 15, 30, 45]))
    cause = random.choice(CAUSES_BY_MONTH_WINTER if day.month in (12, 1, 2) else CAUSES_OTHER)
    btype = random.choice(TYPE_BY_CAUSE[cause])
    loss = random.randrange(2_000, 60_000, 500) * (2 if m["diameter_in"] >= 12 else 1)
    b = dict(break_id=n, main_id=m["main_id"], reported_at=reported, break_type=btype, cause=cause, est_loss_gal=loss)
    breaks.append(b)

# Repairs: the last few breaks are still open (no crew yet, or in progress).
no_repair = {N_BREAKS, N_BREAKS - 2, N_BREAKS - 5, 37}  # 37: an old one that fell through the cracks
in_progress = {N_BREAKS - 1, N_BREAKS - 3, N_BREAKS - 7}
rid = 1
for b in breaks:
    if b["break_id"] in no_repair:
        continue
    crew_id = random.randint(1, len(CREWS))
    started = b["reported_at"] + timedelta(hours=random.randint(1, 10), minutes=random.choice([0, 30]))
    method = METHOD_BY_TYPE[b["break_type"]]
    base = {"Clamp": 3, "Joint Repair": 5, "Pipe Section Replacement": 9}[method]
    if b["break_id"] in in_progress:
        completed, cost = None, None
    else:
        hours = base + random.randint(0, 6) + (2 if crew_id == 4 else 0)
        completed = started + timedelta(hours=hours, minutes=random.choice([0, 15, 30, 45]))
        cost = round(hours * 640 + random.randrange(500, 9000, 25) + (6000 if method == "Pipe Section Replacement" else 0), 2)
    repairs.append(
        dict(repair_id=rid, break_id=b["break_id"], crew_id=crew_id, started_at=started,
             completed_at=completed, repair_method=method, cost_usd=cost)
    )
    rid += 1

out = ["-- 02_seed.sql (generated by scripts/generate_seed.py; do not edit by hand)",
       "-- Run after 01_schema.sql.", "begin;"]
out.append("insert into quiz.pressure_zones (zone_id, zone_name) values")
out.append(",\n".join(f"  ({i}, {q(z)})" for i, z in enumerate(ZONES, start=1)) + ";")
out.append("insert into quiz.crews (crew_id, crew_name, shift) values")
out.append(",\n".join(f"  ({i}, {q(c)}, {q(s)})" for i, (c, s) in enumerate(CREWS, start=1)) + ";")
out.append("insert into quiz.mains (main_id, zone_id, material, diameter_in, length_ft, install_year) values")
out.append(",\n".join(
    f"  ({m['main_id']}, {m['zone_id']}, {q(m['material'])}, {m['diameter_in']}, {m['length_ft']}, {m['install_year']})"
    for m in mains) + ";")
out.append("insert into quiz.breaks (break_id, main_id, reported_at, break_type, cause, est_loss_gal) values")
out.append(",\n".join(
    f"  ({b['break_id']}, {b['main_id']}, {ts(b['reported_at'])}, {q(b['break_type'])}, {q(b['cause'])}, {b['est_loss_gal']})"
    for b in breaks) + ";")
out.append("insert into quiz.repairs (repair_id, break_id, crew_id, started_at, completed_at, repair_method, cost_usd) values")
out.append(",\n".join(
    f"  ({r['repair_id']}, {r['break_id']}, {r['crew_id']}, {ts(r['started_at'])}, "
    f"{ts(r['completed_at']) if r['completed_at'] else 'null'}, {q(r['repair_method'])}, "
    f"{r['cost_usd'] if r['cost_usd'] is not None else 'null'})"
    for r in repairs) + ";")
out.append("commit;")

path = Path(__file__).resolve().parent.parent / "supabase" / "02_seed.sql"
path.write_text("\n".join(out) + "\n")
print(f"wrote {path}: {len(mains)} mains, {len(breaks)} breaks, {len(repairs)} repairs")
