"""Write supabase/04_questions.sql with each hint's expected result computed live.

Run after 01-03 are loaded:  python scripts/build_questions.py
The expected results come from actually running the hint SQL, never typed by hand.
"""

import json
from pathlib import Path

from dotenv import load_dotenv

from questions import QUESTIONS
from quizdb import connect, run_query

load_dotenv()


def dq(s):
    assert "$q$" not in s
    return f"$q${s}$q$"


conn = connect()
lines = ["-- 04_questions.sql (generated by scripts/build_questions.py; do not edit by hand)",
         "-- Run after 03_app.sql.", "begin;"]
for q in QUESTIONS:
    result = run_query(conn, q["hint_sql"])
    print(f"Q{q['id']}: {len(result['rows'])} rows")
    lines.append(
        "insert into public.questions (id, title, prompt, output_columns, order_matters, points, hint_sql, hint_result)\n"
        f"values ({q['id']}, {dq(q['title'])}, {dq(q['prompt'])}, {dq(q['output_columns'])}, "
        f"{str(q['order_matters']).lower()}, {q['points']},\n{dq(q['hint_sql'])},\n"
        f"{dq(json.dumps(result))}::jsonb)\n"
        "on conflict (id) do update set title = excluded.title, prompt = excluded.prompt,\n"
        "  output_columns = excluded.output_columns, order_matters = excluded.order_matters,\n"
        "  points = excluded.points, hint_sql = excluded.hint_sql, hint_result = excluded.hint_result;"
    )
lines.append(f"delete from public.questions where id not in ({', '.join(str(q['id']) for q in QUESTIONS)});")
lines.append("commit;")

out = Path(__file__).resolve().parent.parent / "supabase" / "04_questions.sql"
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out}")
